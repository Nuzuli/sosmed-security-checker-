import re
import sys

def cek_kekuatan_sandi(sandi):
    skor = 0
    saran = []
    
    if len(sandi) >= 12:
        skor += 2
    elif len(sandi) >= 8:
        skor += 1
        saran.append("⚠️ Disarankan sandi minimal 12 karakter")
    else:
        saran.append("❌ Sandi terlalu pendek! Minimal 8 karakter")
    
    if re.search(r"[A-Z]", sandi):
        skor += 1
    else:
        saran.append("❌ Tambahkan huruf besar (A-Z)")
    
    if re.search(r"[a-z]", sandi):
        skor += 1
    else:
        saran.append("❌ Tambahkan huruf kecil (a-z)")
    
    if re.search(r"[0-9]", sandi):
        skor += 1
    else:
        saran.append("❌ Tambahkan angka (0-9)")
    
    if re.search(r"[!@#$%^&*()_+\-=\[\]{};:'\"\\|,.<>\/?]", sandi):
        skor += 1
    else:
        saran.append("⚠️ Tambahkan karakter khusus seperti !@#$%")
    
    return skor, saran

